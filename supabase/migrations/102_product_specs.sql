-- Extra facts for any catalog product. Paver coverage stays on variations.
-- A light, a plant, or a bag of soil can store its own facts here without new columns.

CREATE TABLE IF NOT EXISTS public.product_specs (
  spec_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  base_product_id integer NOT NULL REFERENCES public.base_products (base_product_id) ON DELETE CASCADE,
  spec_name text NOT NULL,
  spec_value text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS product_specs_product_idx ON public.product_specs (base_product_id, sort_order);

ALTER TABLE public.product_specs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can view product specs" ON public.product_specs;
CREATE POLICY "Public can view product specs"
  ON public.product_specs FOR SELECT TO anon, authenticated
  USING (true);

GRANT SELECT ON public.product_specs TO anon, authenticated;
GRANT ALL ON public.product_specs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.product_specs_spec_id_seq TO service_role;
